export const productBySlug = (slug: string) => products.find((p) => p.slug === slug);

export const relatedProducts = (p: Product, n = 4) =>
  products
    .filter((x) => x.slug !== p.slug && (x.material === p.material || x.category === p.category))
    .sort((a, b) => Number(b.material === p.material) - Number(a.material === p.material))
    .slice(0, n);
